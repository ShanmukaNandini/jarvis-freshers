#!/usr/bin/env python3
"""Small Streamlit interface for the Jarvis for Freshers scaffold.

Usage:
    pip install streamlit
    streamlit run streamlit_app.py

Notes:
- This UI is a research-stage demo. It keeps public-demo data synthetic by default.
- Do NOT connect a real inbox until you've configured OAuth, consent, and private storage.
- The AgentFoundry native agent manifest must be generated by the installed IDE; see docs/AGENTFOUNDRY.md.
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent / "src"))

import sqlite3
from datetime import datetime, timezone

import streamlit as st
from jarvis.core import rewrite_resume_structured, rank_jobs, suggest_email_status, daily_digest
from jarvis.jobs import fetch_greenhouse
from jarvis.store import connect, save_application, record_reviewed_event, events

DB_PATH = "jarvis_demo.db"

st.set_page_config(page_title="Jarvis for Freshers — Demo", layout="wide")

st.title("Jarvis for Freshers — Demo UI")
st.sidebar.header("Demo controls")
mode = st.sidebar.radio("Job source:", ["Synthetic demo", "Greenhouse board (read-only)"])

st.sidebar.markdown("""
This demo uses local storage at `./jarvis_demo.db` when you click save. For a public demo, use synthetic data and do not upload personal resumes.
""")

st.header("1) Provide resume and interests")
with st.form("profile_form"):
    resume_text = st.text_area("Paste your resume (plain text)", height=200,
                               placeholder="E.g. Final-year B.Tech in Computer Science. Built a web scraper using Python and requests. Familiar with SQL and pandas.")
    interests_raw = st.text_input("Interests (comma-separated)", value="data, backend, python")
    location = st.text_input("Preferred location (free text)", value="Remote / India")
    eligibility = st.text_input("Work eligibility / visa status (free text)", value="Citizen")
    submitted = st.form_submit_button("Preview tailored resume (no external model used)")

interests = [i.strip() for i in interests_raw.split(",") if i.strip()]

if submitted:
    if not resume_text.strip():
        st.error("Please paste a resume to continue the preview.")
    else:
        st.success("Generated a provenance-backed structured rewrite (rule-based). Review before approving.")
        rewritten = rewrite_resume_structured(resume_text, interests=interests)
        st.subheader("Approval preview (plain text)")
        st.code(rewritten["approval_preview"])
        st.subheader("Source sentences with indices")
        for i, s in enumerate(rewritten["sentences"]):
            st.markdown(f"**[{i}]** {s}")
        st.info("Every claim in the preview links to one or more source sentence indices. The rewrite is deterministic and does not invent facts.")
        approved = st.button("Approve preview (will enable saving job-specific resumes locally)")
        if approved:
            st.success("Preview approved. You can now select jobs and save job-specific application records in the local demo DB.")

st.markdown("---")

st.header("2) Find relevant openings (read-only)")

jobs = []
if mode == "Synthetic demo":
    jobs = [
        {"id": "synth-1", "title": "Python Data Intern", "description": "Work with Python, pandas and SQL to clean datasets.", "fetched_at": datetime.now(timezone.utc).isoformat(), "url": "https://example.com/jobs/synth-1", "source": "synthetic"},
        {"id": "synth-2", "title": "Backend Engineer Intern", "description": "Develop REST APIs in Python. Familiarity with Docker helpful.", "fetched_at": datetime.now(timezone.utc).isoformat(), "url": "https://example.com/jobs/synth-2", "source": "synthetic"},
    ]
else:
    st.info("Provide a verified Greenhouse board token (public boards only). Do not paste private tokens in public demos.")
    board_token = st.text_input("Greenhouse board token", value="")
    if st.button("Fetch Greenhouse jobs"):
        if not board_token.strip():
            st.error("Please enter a board token")
        else:
            try:
                jobs = fetch_greenhouse(board_token.strip())
                st.success(f"Fetched {len(jobs)} jobs from Greenhouse. Results show original URLs and fetched_at timestamps.")
            except Exception as e:
                st.error(f"Failed to fetch: {e}")

# If we have jobs, rank them
if jobs:
    st.subheader("Ranked matches (baseline)")
    profile_text = resume_text or ""
    ranked = rank_jobs(profile_text, interests, jobs)
    for j in ranked:
        st.markdown(f"### {j['title']}")
        st.write(f"Source: {j.get('source', 'unknown')} — URL: {j.get('url')} — fetched_at: {j.get('fetched_at')}")
        st.write(f"Baseline score: {j.get('baseline_score')} — resume hits: {', '.join(j.get('resume_hits',[]))} — interest hits: {', '.join(j.get('interest_hits',[]))}")
        col1, col2 = st.columns(2)
        with col1:
            if st.button(f"Save application — {j['id']}", key=f"save-{j['id']}"):
                db = connect(DB_PATH)
                try:
                    save_application(db, j['id'], j['title'].split()[0], j['title'], j.get('url',''))
                    st.success("Saved application record locally in demo DB.")
                except sqlite3.IntegrityError:
                    st.warning("Application already saved.")
        with col2:
            st.write(j.get('description', ''))

st.markdown("---")

st.header("3) Local application tracker (demo)")
db = connect(DB_PATH)
apps = [dict(r) for r in db.execute("SELECT * FROM applications").fetchall()]
if not apps:
    st.info("No saved applications yet. Save one from the results above.")
else:
    st.subheader("Saved applications")
    for a in apps:
        st.markdown(f"**{a['id']}** — {a['company']} / {a['role']} — status: {a['status']}")

    st.subheader("Record a reviewed event (manual evidence required)")
    sel = st.selectbox("Select application", options=[a['id'] for a in apps])
    source_id = st.text_input("Source message ID (opaque, required)", value="demo-msg-1")
    subject = st.text_input("Message subject (for suggestion)", value="Application received")
    body = st.text_area("Message body (for suggestion)", value="Thank you for applying. We will review your application.")
    suggestion = suggest_email_status(subject, body)
    st.write("Suggested status:", suggestion)
    occurred_at = st.text_input("Occurred at (ISO with timezone)", value=datetime.now(timezone.utc).isoformat())
    evidence = st.text_area("Evidence summary (required)", value="Copied phrase: 'application received'")
    if st.button("Record reviewed event"):
        try:
            ok = record_reviewed_event(db, sel, source_id, suggestion.get('status', 'needs_review'), occurred_at, evidence)
            if ok:
                st.success("Event recorded and application status updated locally.")
            else:
                st.warning("Event ignored (duplicate source_id).")
        except Exception as e:
            st.error(f"Could not record event: {e}")

    st.subheader("Daily digest preview (Asia/Kolkata)")
    evs = events(db)
    today_kolkata = datetime.now(timezone.utc).astimezone().date().isoformat()
    st.code(daily_digest(evs, today_kolkata))

st.markdown("---")
st.header("What this demo DOES NOT do (honest limitations)")
st.write("- No LLM-driven resume rewriting is integrated here; rewrite_preview is a deterministic rule-based extractor. For richer rewrites, integrate a model with a reviewer-in-the-loop.")
st.write("- The AgentFoundry native agent manifest is NOT generated by this repo. Generate it within the installed AgentFoundry IDE (Advanced → Google ADK) and keep credentials private. See docs/AGENTFOUNDRY.md.")
st.write("- No inbox (Gmail) connection is configured. Do not paste real private emails here. Inbox integration requires consent, OAuth scopes and private storage configuration.")
st.write("- Auto-apply or automated outbound email is NOT implemented and must never be enabled without explicit user consent and an audit trail.")

st.caption("If you want, I can help prepare the AgentFoundry ADK steps or add an LLM-backed rewrite once you confirm model availability and private key handling.")
